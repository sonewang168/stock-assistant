/**
 * 取得股票資訊
 */
function getStockInfo(stockId) {
  return TW_STOCKS[stockId] || null;
}

/**
 * 搜尋股票（依名稱或代碼）
 */
function searchStock(keyword) {
  const results = [];
  const kw = keyword.toLowerCase();
  
  for (const [id, info] of Object.entries(TW_STOCKS)) {
    if (id.includes(keyword) || info.name.toLowerCase().includes(kw)) {
      results.push({ id, ...info });
      if (results.length >= 10) break;
    }
  }
  
  return results;
}

/**
 * 取得所有股票
 */
function getAllStocks() {
  return Object.entries(TW_STOCKS).map(([id, info]) => ({ id, ...info }));
}

/**
 * 取得統計
 */
function getStats() {
  const all = Object.values(TW_STOCKS);
  return {
    total: all.length,
    tse: all.filter(s => s.market === 'TSE').length,
    otc: all.filter(s => s.market === 'OTC').length
  };
}

